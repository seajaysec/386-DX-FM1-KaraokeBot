"""Packs firmware/src/app/cards.txt (the help cards) into a C header the screen reads: the texts as byte-pair
tokens (a byte of 128 or more names a pair; the pair table is in the header), each string ending in 0.
    tools/gen_cards.py build/gen/cards.h"""
import collections, sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
cards = []
for line in (root / "firmware/src/app/cards.txt").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    name, title, text = line.split("|", 2)
    cards.append((name, title, text))
for name, title, _ in cards:
    if len(title) > 23:                       # (card_title holds 23 characters)
        raise SystemExit(f"gen_cards: {name}'s title '{title}' is over 23 characters")
strings = [s for _, t, x in cards for s in (t, x)]
for s in strings:
    assert all(32 <= ord(c) < 127 for c in s), s

seqs = [list(s.encode()) + [0] for s in strings]
merges = []
while len(merges) < 127:
    count = collections.Counter()
    for q in seqs:
        for pair in zip(q, q[1:]):
            if 0 not in pair:
                count[pair] += 1
    if not count:
        break
    pair, n = max(count.items(), key=lambda kv: (kv[1], -kv[0][0], -kv[0][1]))
    if n < 3:
        break                                     # (a pair twice saves a byte less than its table entry)
    tok = 128 + len(merges)
    merges.append(pair)
    for k, q in enumerate(seqs):
        r, i = [], 0
        while i < len(q):
            if i + 1 < len(q) and (q[i], q[i + 1]) == pair:
                r.append(tok)
                i += 2
            else:
                r.append(q[i])
                i += 1
        seqs[k] = r

data, off = [], []
for q in seqs:
    off.append(len(data))
    data += q
out = ["/* generated by tools/gen_cards.py from firmware/src/app/cards.txt: do not edit */",
       "enum { " + ", ".join(f"CARD_{n}" for n, _, _ in cards) + ", NCARDS };",
       f"static const uint8_t CARD_PAIR[{len(merges)}][2] = {{" + ", ".join(f"{{{a}, {b}}}" for a, b in merges) + "};",
       f"static const uint16_t CARD_OFF[{2 * len(cards)}] = {{" + ", ".join(map(str, off)) + "};",
       f"static const uint8_t CARD_DATA[{len(data)}] = {{" + ", ".join(map(str, data)) + "};", ""]
Path(sys.argv[1]).write_text("\n".join(out))
raw = sum(len(s) + 1 for s in strings)
print(f"gen_cards: {len(cards)} cards, {raw} bytes as {len(data)} + {2 * len(merges)} (pairs) + {2 * len(off)} (offsets)")
