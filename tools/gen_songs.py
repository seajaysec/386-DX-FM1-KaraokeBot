"""The song in the firmware: Greensleeves (tools/demo_song.mjs makes it, checked against the speech
engine), packed (literal runs and back references, firmware/src/app/factory.c unpacks it) into
build/gen/song_demos.h. The first time 386DX starts it is saved into S1.

    tools/gen_songs.py"""
import base64
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def pack(a):
    # the cheapest stream: at each byte, a literal run (1..128) or a match of 3..130 bytes up to 16383 back
    n = len(a)
    hist, best_match = {}, []
    for i in range(n):
        key = bytes(a[i:i + 3])
        length, offset = 0, 0
        for p in reversed(hist.get(key, [])[-96:]):
            if i - p > 16383:
                break
            k = 0
            while k < 130 and i + k < n and a[p + k] == a[i + k]:
                k += 1
            if k > length:
                length, offset = k, i - p
            if length == 130:
                break
        best_match.append((length, offset))
        hist.setdefault(key, []).append(i)
    cost = [0] * (n + 1)
    choice = [None] * n
    for i in range(n - 1, -1, -1):
        best, pick = 10 ** 9, None
        for k in range(1, min(128, n - i) + 1):
            c = 1 + k + cost[i + k]
            if c < best:
                best, pick = c, (0, k)
        length, offset = best_match[i]
        for k in range(3, min(length, n - i) + 1):
            c = (2 if offset < 128 else 3) + cost[i + k]
            if c < best:
                best, pick = c, (offset, k)
        cost[i], choice[i] = best, pick
    out, i = bytearray(), 0
    while i < n:
        offset, k = choice[i]
        if offset:
            out.append(128 + k - 3)
            out.append(offset if offset < 128 else (offset & 127) | 128)
            if offset >= 128:
                out.append(offset >> 7)
        else:
            out.append(k - 1)
            out.extend(a[i:i + k])
        i += k
    return bytes(out)


def unpack(a):
    out, i = bytearray(), 0
    while i < len(a):
        t = a[i]
        i += 1
        if t < 128:
            out.extend(a[i:i + t + 1])
            i += t + 1
        else:
            off = a[i]
            i += 1
            if off & 128:
                off = (off & 127) | (a[i] << 7)
                i += 1
            for _ in range(t - 125):
                out.append(out[-off])
    return bytes(out)


def main():
    songs = [json.loads(subprocess.check_output(["node", str(root / "tools/demo_song.mjs")], cwd=root))]
    lines = ["/* generated by tools/gen_songs.py: the demo songs, packed; do not edit */"]
    total = 0
    for i, s in enumerate(songs):
        raw = base64.b64decode(s["bytes"])
        packed = pack(raw)
        assert unpack(packed) == raw
        total += len(packed)
        lines.append("static const uint8_t packed_%d[] = {%s};" % (i, ",".join(map(str, packed))))
    lines.append("static const demo_t demos[] = {")
    for i, s in enumerate(songs):
        lines.append("    {%s, packed_%d, sizeof packed_%d}," % (json.dumps(s["name"][:23]), i, i))
    lines.append("};")
    out = root / "build/gen/song_demos.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("demos: %s, %d bytes packed" % (", ".join(s["name"] for s in songs), total))


if __name__ == "__main__":
    main()
